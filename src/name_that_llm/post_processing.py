"""Post-processing module: Prompt clustering & Hungarian bipartite matching.

Enforces the dataset invariant that each unseen prompt produced at most one passage per
frontier model, recovering balanced class distributions and eliminating majority class dominance.
"""

from typing import List, Optional, Tuple
import numpy as np
from scipy.cluster.hierarchy import fcluster, linkage
from scipy.optimize import linear_sum_assignment
from scipy.spatial.distance import squareform
from sklearn.feature_extraction.text import TfidfVectorizer

from name_that_llm.config import NUM_CLASSES, TARGET_MODELS


def sinkhorn_balance(
    probabilities: np.ndarray,
    num_iterations: int = 50,
    min_samples: int = 50,
) -> np.ndarray:
    """Balance the probability matrix using Sinkhorn-Knopp algorithm so every class
    receives uniform total probability mass (N / K), aligning directly with the competition Balanced Accuracy metric.

    Args:
        probabilities: (N, K) array of predicted class probabilities.
        num_iterations: Number of Sinkhorn normalization steps (default: 50).
        min_samples: Minimum test samples required before applying balancing.

    Returns:
        (N, K) array of balanced probabilities.
    """
    p = np.asarray(probabilities, dtype=np.float64).copy()
    n_samples, n_classes = p.shape
    if n_samples < min_samples:
        return p
    target = np.full(n_classes, n_samples / float(n_classes))
    for _ in range(num_iterations):
        p *= target / (p.sum(axis=0) + 1e-12)
        p /= p.sum(axis=1, keepdims=True) + 1e-12
    return p


def cluster_passages_by_prompt(
    texts: List[str],
    distance_threshold: float = 0.90,
    max_features: Optional[int] = None,
) -> np.ndarray:
    """Cluster text passages by prompt topic using TF-IDF cosine distance and average linkage.

    Args:
        texts: List of passages to cluster.
        distance_threshold: Linkage distance cut threshold (0.90 validated optimal on CV).
        max_features: Maximum TF-IDF vocabulary features.

    Returns:
        1D array of integer cluster assignments for each text.
    """
    if len(texts) < 2:
        return np.ones(len(texts), dtype=int)

    tfidf = TfidfVectorizer(
        stop_words="english",
        sublinear_tf=True,
        max_features=max_features,
    ).fit_transform(texts)

    # Cosine distance = 1 - cosine_similarity
    distances = np.clip(1.0 - (tfidf @ tfidf.T).toarray(), 0.0, 2.0)
    np.fill_diagonal(distances, 0.0)

    # Hierarchical clustering with average linkage
    condensed = squareform(distances, checks=False)
    z = linkage(condensed, method="average")
    cluster_labels = fcluster(z, distance_threshold, criterion="distance")
    return cluster_labels


def exclusive_marginals(probabilities: np.ndarray) -> np.ndarray:
    """Exact Bayesian posterior conditioning for small clusters (2 <= N <= 6).

    Computes exact conditional probability that row i was generated by class c,
    given the constraint that all N rows in the cluster have distinct classes.
    """
    p = np.asarray(probabilities, dtype=np.float64)
    p = p / (p.sum(axis=1, keepdims=True) + 1e-12)
    n, k = p.shape
    if n > k or n > 6 or n <= 1:
        return p.copy()

    full = (1 << n) - 1
    f = np.zeros((k + 1, 1 << n), dtype=np.float64)
    b = np.zeros_like(f)
    f[0, 0] = 1.0
    b[k, 0] = 1.0

    for c in range(k):
        f[c + 1] = f[c]
        for mask in range(1, full + 1):
            for i in range(n):
                if mask & (1 << i):
                    f[c + 1, mask] += p[i, c] * f[c, mask ^ (1 << i)]

    for c in range(k - 1, -1, -1):
        b[c] = b[c + 1]
        for mask in range(1, full + 1):
            for i in range(n):
                if mask & (1 << i):
                    b[c, mask] += p[i, c] * b[c + 1, mask ^ (1 << i)]

    z = f[k, full]
    if z <= 1e-15:
        return p.copy()

    q = np.zeros_like(p)
    for i in range(n):
        remaining = full ^ (1 << i)
        for c in range(k):
            subset = remaining
            while True:
                q[i, c] += p[i, c] * f[c, subset] * b[c + 1, remaining ^ subset] / z
                if subset == 0:
                    break
                subset = (subset - 1) & remaining

    return q / (q.sum(axis=1, keepdims=True) + 1e-12)


def match_clusters_hungarian(
    probabilities: np.ndarray,
    clusters: np.ndarray,
    num_classes: int = NUM_CLASSES,
) -> Tuple[np.ndarray, np.ndarray]:
    """Perform Hungarian bipartite assignment within prompt clusters to maximize joint likelihood.

    Args:
        probabilities: (N, K) array of predicted class probabilities.
        clusters: (N,) array of integer cluster IDs.
        num_classes: Number of candidate models (18).

    Returns:
        (posteriors, predicted_indices):
            posteriors: (N, K) conditioned probability array.
            predicted_indices: (N,) optimal class indices.
    """
    p = np.asarray(probabilities, dtype=np.float64)
    p = p / (p.sum(axis=1, keepdims=True) + 1e-12)
    clusters = np.asarray(clusters)
    n_samples = len(p)
    predicted_indices = np.zeros(n_samples, dtype=int)
    posteriors = p.copy()

    for cluster_id in np.unique(clusters):
        members = np.flatnonzero(clusters == cluster_id)
        m = len(members)

        if m <= 1:
            predicted_indices[members[0]] = np.argmax(p[members[0]])
            continue

        c_log_p = np.log(np.clip(p[members], 1e-12, 1.0))

        if m <= num_classes:
            # Strict 1-to-1 bipartite matching: maximize sum of log probabilities
            row_ind, col_ind = linear_sum_assignment(-c_log_p)
            for r, c in zip(row_ind, col_ind):
                predicted_indices[members[r]] = c
                posteriors[members[r]] = 1e-6
                posteriors[members[r], c] = 1.0
            posteriors[members] /= posteriors[members].sum(axis=1, keepdims=True)
        else:
            # Capacity-expanded matching for oversized clusters (>18)
            capacity = int(np.ceil(m / float(num_classes)))
            expanded_log_p = np.repeat(c_log_p, capacity, axis=1)
            expanded_classes = np.repeat(np.arange(num_classes), capacity)
            row_ind, col_ind = linear_sum_assignment(-expanded_log_p)
            for r, c in zip(row_ind, col_ind):
                assigned_class = expanded_classes[c]
                predicted_indices[members[r]] = assigned_class
                posteriors[members[r]] = 1e-6
                posteriors[members[r], assigned_class] = 1.0
            posteriors[members] /= posteriors[members].sum(axis=1, keepdims=True)

    return posteriors, predicted_indices
