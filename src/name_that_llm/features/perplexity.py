"""Tokenizer fingerprinting, compression ratios, and vocabulary fragmentation features.

Different LLM providers and open-weight models utilize distinct BPE tokenizers
(e.g., OpenAI's cl100k_base & o200k_base, Alibaba's Qwen2.5 152k BPE, Zhipu AI's GLM-4 151k BPE).
When a text passage is generated by a specific LLM, tokenizing it with that model's native
tokenizer yields minimal fragmentation, higher characters-per-token, and characteristic
subword length distributions compared to foreign tokenizers.
"""

import bz2
import zlib
from typing import Any, Dict, List, Optional
import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, TransformerMixin
import tiktoken
from transformers import AutoTokenizer


class TokenizerFeatureExtractor(BaseEstimator, TransformerMixin):
    """Extracts subword compression ratios, cross-tokenizer token count divergences,
    and byte-level entropy signatures across OpenAI, Qwen, and GLM tokenizers.
    """

    def __init__(
        self,
        use_qwen: bool = True,
        use_glm: bool = True,
        use_tiktoken: bool = True,
        use_compression: bool = True,
    ) -> None:
        self.use_qwen = use_qwen
        self.use_glm = use_glm
        self.use_tiktoken = use_tiktoken
        self.use_compression = use_compression
        self.feature_names_: List[str] = []

        self._enc_cl100k: Optional[Any] = None
        self._enc_o200k: Optional[Any] = None
        self._tok_qwen: Optional[Any] = None
        self._tok_glm: Optional[Any] = None

    def _init_tokenizers(self) -> None:
        """Lazy-initialize tokenizers only when needed."""
        if self.use_tiktoken and self._enc_cl100k is None:
            self._enc_cl100k = tiktoken.get_encoding("cl100k_base")
            self._enc_o200k = tiktoken.get_encoding("o200k_base")

        if self.use_qwen and self._tok_qwen is None:
            self._tok_qwen = AutoTokenizer.from_pretrained(
                "Qwen/Qwen2.5-7B",
                use_fast=True,
            )

        if self.use_glm and self._tok_glm is None:
            self._tok_glm = AutoTokenizer.from_pretrained(
                "THUDM/glm-4-9b-chat",
                trust_remote_code=True,
            )

    def fit(self, X, y=None):
        self._init_tokenizers()
        return self

    def transform(self, X) -> np.ndarray:
        self._init_tokenizers()
        if isinstance(X, (pd.Series, np.ndarray)):
            texts = X.tolist()
        else:
            texts = list(X)

        feature_rows: List[Dict[str, float]] = []
        for text in texts:
            feature_rows.append(self._extract_features_single(str(text)))

        df_feat = pd.DataFrame(feature_rows)
        self.feature_names_ = list(df_feat.columns)
        return df_feat.values

    def get_feature_names_out(self, input_features=None) -> List[str]:
        return self.feature_names_

    def _extract_features_single(self, text: str) -> Dict[str, float]:
        feats: Dict[str, float] = {}
        raw_bytes = text.encode("utf-8")
        chars = max(len(text), 1)
        bytes_len = max(len(raw_bytes), 1)
        words = max(len(text.split()), 1)

        # 1. Byte-level compression ratios (entropy signatures)
        if self.use_compression:
            feats["comp_zlib_ratio"] = len(zlib.compress(raw_bytes, level=6)) / bytes_len
            feats["comp_bz2_ratio"] = len(bz2.compress(raw_bytes)) / bytes_len

        # 2. Tokenize with available tokenizers
        n_cl = None
        n_o200 = None
        n_qwen = None
        n_glm = None

        if self.use_tiktoken and self._enc_cl100k and self._enc_o200k:
            cl_toks = self._enc_cl100k.encode(text)
            o200_toks = self._enc_o200k.encode(text)
            n_cl = max(len(cl_toks), 1)
            n_o200 = max(len(o200_toks), 1)

            feats["tok_cl100k_count"] = float(n_cl)
            feats["tok_o200k_count"] = float(n_o200)
            feats["tok_ratio_o200k_cl100k"] = n_o200 / n_cl
            feats["tok_chars_per_cl100k"] = chars / n_cl
            feats["tok_chars_per_o200k"] = chars / n_o200
            feats["tok_bytes_per_cl100k"] = bytes_len / n_cl
            feats["tok_bytes_per_o200k"] = bytes_len / n_o200
            feats["tok_words_per_cl100k"] = words / n_cl
            feats["tok_words_per_o200k"] = words / n_o200

            # Subword byte-length fragmentation under o200k
            if len(o200_toks) > 0:
                o200_byte_lens = [len(self._enc_o200k.decode_single_token_bytes(t)) for t in o200_toks]
                feats["tok_o200k_mean_byte_len"] = float(np.mean(o200_byte_lens))
                feats["tok_o200k_std_byte_len"] = float(np.std(o200_byte_lens))
                feats["tok_o200k_short_token_ratio"] = sum(1 for l in o200_byte_lens if l <= 2) / n_o200
            else:
                feats["tok_o200k_mean_byte_len"] = 0.0
                feats["tok_o200k_std_byte_len"] = 0.0
                feats["tok_o200k_short_token_ratio"] = 0.0

        if self.use_qwen and self._tok_qwen:
            qwen_toks = self._tok_qwen.encode(text)
            n_qwen = max(len(qwen_toks), 1)
            feats["tok_qwen_count"] = float(n_qwen)
            feats["tok_chars_per_qwen"] = chars / n_qwen
            feats["tok_bytes_per_qwen"] = bytes_len / n_qwen
            feats["tok_words_per_qwen"] = words / n_qwen

            if len(qwen_toks) > 0:
                # Subword character fragmentation
                qwen_str_lens = [len(self._tok_qwen.decode([t])) for t in qwen_toks]
                feats["tok_qwen_mean_char_len"] = float(np.mean(qwen_str_lens))
                feats["tok_qwen_std_char_len"] = float(np.std(qwen_str_lens))
                feats["tok_qwen_short_token_ratio"] = sum(1 for l in qwen_str_lens if l <= 2) / n_qwen
            else:
                feats["tok_qwen_mean_char_len"] = 0.0
                feats["tok_qwen_std_char_len"] = 0.0
                feats["tok_qwen_short_token_ratio"] = 0.0

        if self.use_glm and self._tok_glm:
            glm_toks = self._tok_glm.encode(text)
            n_glm = max(len(glm_toks), 1)
            feats["tok_glm_count"] = float(n_glm)
            feats["tok_chars_per_glm"] = chars / n_glm
            feats["tok_bytes_per_glm"] = bytes_len / n_glm
            feats["tok_words_per_glm"] = words / n_glm

            if len(glm_toks) > 0:
                glm_str_lens = [len(self._tok_glm.decode([t])) for t in glm_toks]
                feats["tok_glm_mean_char_len"] = float(np.mean(glm_str_lens))
                feats["tok_glm_std_char_len"] = float(np.std(glm_str_lens))
                feats["tok_glm_short_token_ratio"] = sum(1 for l in glm_str_lens if l <= 2) / n_glm
            else:
                feats["tok_glm_mean_char_len"] = 0.0
                feats["tok_glm_std_char_len"] = 0.0
                feats["tok_glm_short_token_ratio"] = 0.0

        # 3. Cross-tokenizer ratios
        if n_cl is not None:
            if n_qwen is not None:
                feats["tok_ratio_qwen_cl100k"] = n_qwen / n_cl
            if n_glm is not None:
                feats["tok_ratio_glm_cl100k"] = n_glm / n_cl

        if n_o200 is not None:
            if n_qwen is not None:
                feats["tok_ratio_qwen_o200k"] = n_qwen / n_o200
            if n_glm is not None:
                feats["tok_ratio_glm_o200k"] = n_glm / n_o200

        if n_qwen is not None and n_glm is not None:
            feats["tok_ratio_qwen_glm"] = n_qwen / n_glm

        return feats
