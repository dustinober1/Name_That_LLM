    "                'avg_sentence_len_words': w_count / s_count,\n",
    "                'avg_sentence_len_chars': chars / s_count,\n",
    "                'std_sentence_length': float(np.std(sent_lens)) if sent_lens else 0.0,\n",
    "                'ttr_lexical_diversity': len(set(w.lower() for w in words)) / w_count,\n",
