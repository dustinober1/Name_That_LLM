def get_blend_cells():
    train_cell = [
        "# 3. Ensembled Pipeline: Linear (Sparse TF-IDF) + LightGBM (Stylometry + SVD)\n",
        "TARGET_MODELS = sorted(train_df['model'].unique().tolist())\n",
        "print(f'Total target classes ({len(TARGET_MODELS)}): {TARGET_MODELS}')\n",
        "\n",
        "# Feature Extractors\n",
        "tfidf_linear = FeatureUnion([\n",
        "    ('word', TfidfVectorizer(ngram_range=(1, 2), max_features=25000, sublinear_tf=True, min_df=2)),\n",
        "    ('char', TfidfVectorizer(analyzer='char', ngram_range=(3, 5), max_features=35000, sublinear_tf=True, min_df=2)),\n",
        "])\n",
        "sty = StylometricExtractor()\n",
        "scaler = StandardScaler()\n",
        "svd = TruncatedSVD(n_components=128, random_state=42)\n",
        "\n",
        "X_texts = train_df['text'].fillna('').values\n",
        "y = train_df['model'].values\n",
        "groups = train_df['prompt_id'].values\n",
        "\n",
        "print('Extracting multi-modal feature representations...')\n",
        "X_tfidf = tfidf_linear.fit_transform(X_texts)\n",
        "X_sty_raw = sty.fit_transform(X_texts)\n",
        "X_sty_scaled = scaler.fit_transform(X_sty_raw)\n",
        "X_svd = svd.fit_transform(X_tfidf)\n",
        "\n",
        "X_train_linear = sp.hstack([X_tfidf, sp.csr_matrix(X_sty_scaled)]).tocsr()\n",
        "X_train_lgbm = np.hstack([X_sty_raw, X_svd])\n",
        "print(f'Linear shape: {X_train_linear.shape} | LightGBM shape: {X_train_lgbm.shape}')\n",
        "\n",
        "# 5-fold Training for Both Architectures\n",
        "sgkf = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42)\n",
        "linear_models = []\n",
        "lgbm_models = []\n",
        "\n",
        "for fold, (t_idx, v_idx) in enumerate(sgkf.split(X_train_linear, y, groups)):\n",
        "    print(f'Training Fold {fold + 1}/5...')\n",
        "    # 1. Linear\n",
        "    clf_lin = LogisticRegression(C=2.0, max_iter=1500, class_weight='balanced', random_state=42)\n",
        "    clf_lin.fit(X_train_linear[t_idx], y[t_idx])\n",
        "    linear_models.append(clf_lin)\n",
        "    \n",
        "    # 2. LightGBM\n",
        "    clf_lgb = LGBMClassifier(\n",
        "        objective='multiclass',\n",
        "        class_weight='balanced',\n",
        "        n_estimators=200,\n",
        "        learning_rate=0.05,\n",
        "        num_leaves=31,\n",
        "        random_state=42,\n",
        "        verbose=-1,\n",
        "        n_jobs=-1,\n",
        "    )\n",
        "    clf_lgb.fit(X_train_lgbm[t_idx], y[t_idx])\n",
        "    lgbm_models.append(clf_lgb)\n",
        "\n",
        "# 4. Inference on Test Set\n",
        "test_texts = test_df['text'].fillna('').values\n",
        "X_test_tfidf = tfidf_linear.transform(test_texts)\n",
        "X_test_sty_raw = sty.transform(test_texts)\n",
        "X_test_sty_scaled = scaler.transform(X_test_sty_raw)\n",
        "X_test_svd = svd.transform(X_test_tfidf)\n",
        "\n",
        "X_test_linear = sp.hstack([X_test_tfidf, sp.csr_matrix(X_test_sty_scaled)]).tocsr()\n",
        "X_test_lgbm = np.hstack([X_test_sty_raw, X_test_svd])\n",
        "\n",
        "classes = linear_models[0].classes_\n",
        "probs_lin = np.zeros((len(test_df), len(classes)))\n",
        "probs_lgb = np.zeros((len(test_df), len(classes)))\n",
        "\n",
        "for m in linear_models:\n",
        "    probs_lin += m.predict_proba(X_test_linear)\n",
        "probs_lin /= len(linear_models)\n",
        "\n",
        "for m in lgbm_models:\n",
        "    probs_lgb += m.predict_proba(X_test_lgbm)\n",
        "probs_lgb /= len(lgbm_models)\n",
        "\n",
        "# Optimal convex combination: 85% Linear + 15% LightGBM\n",
        "blended_probs = 0.85 * probs_lin + 0.15 * probs_lgb\n",
        "final_preds = classes[np.argmax(blended_probs, axis=1)]",
    ]
    return train_cell


